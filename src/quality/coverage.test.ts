// Recorded from Vitest 3 with Istanbul's cobertura reporter: method lines repeat the class's.
const ISTANBUL_COBERTURA = `<?xml version="1.0" ?>
<!DOCTYPE coverage SYSTEM "http://cobertura.sourceforge.net/xml/coverage-04.dtd">
<coverage lines-valid="3" lines-covered="2" line-rate="0.66" version="0.1">
  <sources>
    <source>/w/vt</source>
  </sources>
  <packages>
    <package name="main" line-rate="0.66">
      <classes>
        <class name="sum.ts" filename="src/sum.ts" line-rate="0.66">
          <methods>
            <method name="sum" hits="2" signature="()V">
              <lines>
                <line number="1" hits="2"/>
              </lines>
            </method>
          </methods>
          <lines>
            <line number="2" hits="2" branch="false"/>
            <line number="6" hits="1" branch="true" condition-coverage="50% (1/2)"/>
            <line number="9" hits="0" branch="true" condition-coverage="0% (0/2)"/>
          </lines>
        </class>
      </classes>
    </package>
  </packages>
</coverage>
`;

describe('parseCobertura', () => {
  it('reads each class’s lines and the source directories', () => {
    expect(parseCobertura(COVERAGE_PY_XML)).toEqual({
      files: [
        { path: '__init__.py', hits: new Map() },
        {
          path: 'calc.py',
          hits: new Map([
            [1, 1],
            [2, 1],
            [5, 1],
            [6, 0],
          ]),
        },
      ],
      sources: ['/w/pkg'],
    });
    expect(hits(parseCobertura(ISTANBUL_COBERTURA))).toEqual({
      'src/sum.ts': [
        [2, 2],
        [6, 1],
        [9, 0],
      ],
    });
  });

  it('reads a report with no packages, classes or sources', () => {
    expect(parseCobertura('<coverage/>')).toEqual({ files: [], sources: [] });
    expect(parseCobertura('<coverage><packages/></coverage>')).toEqual({ files: [], sources: [] });
    expect(
      parseCobertura('<coverage><sources/><packages><package/></packages></coverage>'),
    ).toEqual({ files: [], sources: [] });
    expect(
      parseCobertura('<coverage><packages><package><classes/></package></packages></coverage>'),
    ).toEqual({ files: [], sources: [] });
  });

  it('throws an engine error for another document or a bad count', () => {
    expect(() => parseCobertura('<report/>')).toThrow(
      new EngineError('a Cobertura report has an unexpected shape'),
    );
    const bad =
      '<coverage><packages><package><classes><class filename="a.py"><lines><line number="1" hits=""/></lines></class></classes></package></packages></coverage>';
    expect(() => parseCobertura(bad)).toThrow('a hit count ""');
  });
});

