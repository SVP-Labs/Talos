describe('parseClover', () => {
  it('reads statement and condition lines, never a method’s declaration', () => {
    expect(hits(parseClover(PHPUNIT_CLOVER))).toEqual({
      '/w/src/helpers.php': [[3, 1]],
      '/w/src/Calculator.php': [
        [13, 2],
        [18, 0],
      ],
    });
    expect(hits(parseClover(ISTANBUL_CLOVER))).toEqual({
      '/w/vt/src/sum.ts': [
        [2, 2],
        [6, 1],
        [9, 0],
      ],
    });
  });

  it('reads a file with no lines and a project with no files', () => {
    expect(
      hits(parseClover('<coverage><project><file name="a.php"/></project></coverage>')),
    ).toEqual({ 'a.php': [] });
    expect(parseClover('<coverage><project/></coverage>')).toEqual({ files: [], sources: [] });
    expect(parseClover('<coverage><project><package name="p"/></project></coverage>')).toEqual({
      files: [],
      sources: [],
    });
    expect(parseClover('<coverage><project><package/></project></coverage>')).toEqual({
      files: [],
      sources: [],
    });
  });

  it('throws an engine error for another document', () => {
    expect(() => parseClover('<coverage/>')).toThrow(
      new EngineError('a Clover report has an unexpected shape'),
    );
  });
});

describe('toLineCoverage', () => {
  it('names files as the locator does, drops what it rejects and merges what it joins', () => {
    const raw: RawCoverage = {
      files: [
        { path: './src/a.ts', hits: new Map([[1, 1]]) },
        {
          path: 'src/a.ts',
          hits: new Map([
            [1, 0],
            [2, 0],
          ]),
        },
        { path: '/elsewhere/b.ts', hits: new Map([[1, 1]]) },
      ],
      sources: ['/w'],
    };
    const seen: (readonly string[])[] = [];
    const coverage = toLineCoverage(raw, (path, sources) => {
      seen.push(sources);
      return path.startsWith('/') ? undefined : path.replace(/^\.\//, '');
    });
    expect(lines(coverage)).toEqual({ 'src/a.ts': { executable: [1, 2], covered: [1] } });
    expect(seen).toEqual([['/w'], ['/w'], ['/w']]);
  });
});

describe('mergeCoverage', () => {
  it('covers a line either run covered', () => {
    const first: LineCoverage = new Map([
      ['a.ts', { executable: new Set([1, 2]), covered: new Set([1]) }],
    ]);
    const second: LineCoverage = new Map([
      ['a.ts', { executable: new Set([2, 3]), covered: new Set([2]) }],
      ['b.ts', { executable: new Set([1]), covered: new Set<number>() }],
    ]);
    expect(lines(mergeCoverage(first, second))).toEqual({
      'a.ts': { executable: [1, 2, 3], covered: [1, 2] },
      'b.ts': { executable: [1], covered: [] },
    });
  });
});
