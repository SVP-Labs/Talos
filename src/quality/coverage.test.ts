import { describe, expect, it } from 'vitest';
import {
  type LineCoverage,
  mergeCoverage,
  parseClover,
  parseCobertura,
  parseLcov,
  type RawCoverage,
  toLineCoverage,
} from './coverage.js';
import { EngineError } from '../core/check.js';

function hits(raw: RawCoverage): Record<string, [number, number][]> {
  return Object.fromEntries(raw.files.map((file) => [file.path, [...file.hits]]));
}

type Lines = Record<string, { executable: number[]; covered: number[] }>;

function lines(coverage: LineCoverage): Lines {
  return Object.fromEntries(
    [...coverage].map(([file, entry]) => [
      file,
      { executable: [...entry.executable], covered: [...entry.covered] },
    ]),
  );
}

// Recorded from Vitest 3 with the v8 provider (`--coverage.reporter=lcovonly`).
const VITEST_LCOV = `TN:
SF:src/sum.ts
FN:1,sum
FNF:1
FNH:1
FNDA:2,sum
DA:2,2
DA:6,1
DA:7,1
DA:9,0
LF:4
LH:3
BRDA:6,0,0,1
BRF:1
BRH:1
end_of_record
`;

// Recorded from coverage.py 7 (`--cov-report=lcov`): a file with no lines, then one with lines.
const COVERAGE_PY_LCOV = `SF:pkg/__init__.py
end_of_record
SF:pkg/calc.py
DA:1,1
DA:2,1
DA:5,1
DA:6,0
LF:4
LH:3
end_of_record
`;

describe('parseLcov', () => {
  it('reads each file’s DA lines', () => {
    expect(parseLcov(VITEST_LCOV)).toEqual({
      files: [
        {
          path: 'src/sum.ts',
          hits: new Map([
            [2, 2],
            [6, 1],
            [7, 1],
            [9, 0],
          ]),
        },
      ],
      sources: [],
    });
    expect(hits(parseLcov(COVERAGE_PY_LCOV))).toEqual({
      'pkg/__init__.py': [],
      'pkg/calc.py': [
        [1, 1],
        [2, 1],
        [5, 1],
        [6, 0],
      ],
    });
  });

  it('adds repeated lines, reads checksummed and CRLF lines, and ignores stray DA lines', () => {
    const text =
      'DA:1,1\r\nSF:a.rs\r\nDA:3,1,abc\r\nDA:3,2\r\nDA:4,-1\r\nDA:0,5\r\nend_of_record\r\n';
    expect(hits(parseLcov(text))).toEqual({
      'a.rs': [
        [3, 3],
        [4, 0],
      ],
    });
  });

  it('throws an engine error for a count that is not a number', () => {
    expect(() => parseLcov('SF:a.ts\nDA:x,1\n')).toThrow(
      new EngineError('a coverage report has a line "x", which is not a number'),
    );
    expect(() => parseLcov('SF:a.ts\nDA:1\n')).toThrow('a hit count ""');
  });
});

