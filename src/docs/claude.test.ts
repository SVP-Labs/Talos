import { existsSync } from 'node:fs';
import { lint } from 'markdownlint-cli2/markdownlint/promise';
import { describe, expect, it } from 'vitest';
import {
  claudeBlocks,
  KIT_BEGIN,
  KIT_END,
  kitBlock,
  loadKitTemplate,
  PROJECT_BLOCK_CAP,
  renderClaudeMd,
  sameKitBlock,
} from './claude.js';
import { MARKDOWNLINT_RULES } from '../checks/docs/markdownlint.js';
import { parseConfig } from '../config/load.js';

const config = parseConfig('name: Notebook\nprefix: NB\n');
const template = loadKitTemplate();

describe('kitBlock', () => {
  const block = kitBlock(template, config);

  it("fills in the project's name, prefix and paths, between the markers", () => {
    expect(block.startsWith(`${KIT_BEGIN}\n`)).toBe(true);
    expect(block.endsWith(`\n${KIT_END}`)).toBe(true);
    expect(block).toContain('# Notebook');
    expect(block).toContain('`[NB-<N>]: <what changed>`');
    expect(block).toContain('`docs/requirements`');
    expect(block).not.toMatch(/\{\{\w+\}\}/);
  });

  it('links to the documents Talos ships', () => {
    const links = [...block.matchAll(/blob\/main\/(\S+)$/gm)].map((match) => match[1] ?? '');
    expect(links).toEqual(['ENGINEERING.md', 'docs/agents.md']);
    for (const path of links) {
      expect(existsSync(new URL(`../../${path}`, import.meta.url))).toBe(true);
    }
  });

  it('passes markdownlint, even with a long name and paths', async () => {
    const long = parseConfig(
      'name: A-Rather-Long-Project-Name\nprefix: ABCDEF\n' +
        'docs: { glossary: documentation/glossary.md, briefs: documentation/requirements }\n',
    );
    const results = await lint({
      strings: {
        'CLAUDE.md': `${renderClaudeMd(undefined, { config: long })}\n## Ours\n\nUse tabs.\n`,
      },
      config: MARKDOWNLINT_RULES,
      noInlineConfig: true,
      handleRuleFailures: true,
    });
    expect(results).toEqual({ 'CLAUDE.md': [] });
  });
});

describe('renderClaudeMd', () => {
  it("puts the block first and keeps the project's own instructions on a rerun", () => {
    const first = renderClaudeMd('# Ours\n\nUse tabs.\n', { config }, template);
    expect(first.startsWith(KIT_BEGIN)).toBe(true);
    expect(first.endsWith(`${KIT_END}\n\n# Ours\n\nUse tabs.\n`)).toBe(true);
    const renamed = renderClaudeMd(first, { config: { ...config, prefix: 'NC' } }, template);
    expect(renamed).toContain('`NC-<N>`');
    expect(renamed).not.toContain('`NB-<N>`');
    expect(renamed.endsWith('# Ours\n\nUse tabs.\n')).toBe(true);
    expect(renderClaudeMd(undefined, { config }, template)).toBe(`${kitBlock(template, config)}\n`);
  });
});

describe('claudeBlocks', () => {
  it('finds the kit block and counts the project lines around it', () => {
    const text = ['', 'Intro.', KIT_BEGIN, 'kit', KIT_END, '', '## Ours', '', 'One.', ''].join(
      '\n',
    );
    expect(claudeBlocks(text)).toEqual({
      kit: { line: 3, endLine: 5, text: `${KIT_BEGIN}\nkit\n${KIT_END}` },
      project: { line: 2, endLine: 9, lines: 3 },
    });
  });

  it('has no kit block without both markers, in order', () => {
    expect(claudeBlocks(`${KIT_END}\n${KIT_BEGIN}\nx`).kit).toBeUndefined();
    expect(claudeBlocks(`${KIT_BEGIN}\n${KIT_END}\n`)).toEqual({
      kit: { line: 1, endLine: 2, text: `${KIT_BEGIN}\n${KIT_END}` },
    });
  });

  it('caps the project block at a size an agent reads every time', () => {
    expect(PROJECT_BLOCK_CAP).toBe(60);
  });
});

describe('sameKitBlock', () => {
  const block = kitBlock(template, config);

  it('ignores the generated note and trailing spaces, and nothing else', () => {
    const versioned = block.replace(
      /^<!-- Generated by Talos.*-->$/m,
      '<!-- Generated by Talos 0.1.0. -->',
    );
    expect(sameKitBlock(versioned.replaceAll('\n', '  \r\n'), block)).toBe(true);
    expect(sameKitBlock(block.replace('Notebook', 'Notepad'), block)).toBe(false);
  });
});
