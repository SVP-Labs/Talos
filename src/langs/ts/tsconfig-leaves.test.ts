import { mkdir, mkdtemp, symlink, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';
import { tsconfigLeaves } from './tsconfig-leaves.js';

describe('tsconfigLeaves', () => {
  async function component(files: Record<string, string>): Promise<string> {
    const dir = await mkdtemp(join(tmpdir(), 'tsconfig-leaves-'));
    for (const [name, text] of Object.entries(files)) {
      await mkdir(join(dir, name, '..'), { recursive: true });
      await writeFile(join(dir, name), text);
    }
    return dir;
  }

  it('stays inside a chain of relative tsconfigs that name nothing outside', async () => {
    const dir = await component({
      'tsconfig.json':
        '{\n  // ours\n  "extends": "./tsconfig.talos.json",\n  "include": ["src"]\n}',
      'tsconfig.talos.json':
        '{ "//": "Generated by Talos.", "compilerOptions": { "strict": true } }',
    });
    expect(await tsconfigLeaves(dir)).toBe(false);
    expect(await tsconfigLeaves(join(dir, 'none'))).toBe(false);
  });

  it('leaves through an extended file, a reference or an absolute path', async () => {
    const extended = await component({
      'tsconfig.json': '{ "extends": "./configs/base" }',
      'configs/base.json': '{ "include": ["../../shared/**"] }',
    });
    const referenced = await component({
      'tsconfig.json': '{ "references": [{ "path": "./packages/a" }] }',
      'packages/a/tsconfig.json': '{ "extends": "../../../tsconfig.base.json" }',
    });
    const absolute = await component({ 'tsconfig.json': '{ "files": ["/opt/types.d.ts"] }' });
    expect(await tsconfigLeaves(extended)).toBe(true);
    expect(await tsconfigLeaves(referenced)).toBe(true);
    expect(await tsconfigLeaves(absolute)).toBe(true);
  });

  it.each([
    ['a bare directory', 'packages/a', 'packages/a/tsconfig.json'],
    ['a dotted directory', './packages/a', 'packages/a/tsconfig.json'],
    ['a bare file', 'packages/a/tsconfig.app.json', 'packages/a/tsconfig.app.json'],
  ])('follows a reference to %s into what it extends', async (_, path, target) => {
    const outside = await component({
      'tsconfig.json': `{ "references": [{ "path": "${path}" }], }`,
      [target]: '{ "extends": "../../../tsconfig.base.json" }',
    });
    const inside = await component({
      'tsconfig.json': `{ "references": [{ "path": "${path}" }] }`,
      [target]: '{ "extends": "../../tsconfig.base.json" }',
      'tsconfig.base.json': '{ /* shared */ "compilerOptions": {} }',
    });
    expect(await tsconfigLeaves(outside)).toBe(true);
    expect(await tsconfigLeaves(inside)).toBe(false);
  });

  it('follows each relative base of an extends list, and no package', async () => {
    const dir = await component({
      'tsconfig.json': '{ "extends": ["@tsconfig/node22/tsconfig.json", "./configs/strict"] }',
      'configs/strict.json': '{ "extends": "../../outer.json" }',
    });
    const packaged = await component({
      'tsconfig.json': '{ "extends": "@tsconfig/node22/tsconfig.json" }',
    });
    expect(await tsconfigLeaves(dir)).toBe(true);
    expect(await tsconfigLeaves(packaged)).toBe(false);
  });

  it("keeps Stryker's rewrite for a tsconfig it can't read", async () => {
    const dir = await component({ 'tsconfig.json': '{ "extends": ' });
    const shape = await component({ 'tsconfig.json': '{ "references": "packages/a" }' });
    expect(await tsconfigLeaves(dir)).toBe(true);
    expect(await tsconfigLeaves(shape)).toBe(true);
  });

  it('keeps the rewrite when a tsconfig fails to read for any reason but its absence', async () => {
    const directory = await component({ 'tsconfig.json/keep': '' });
    const looped = await component({});
    await symlink(join(looped, 'tsconfig.json'), join(looped, 'tsconfig.json'));
    const referenced = await component({
      'tsconfig.json': '{ "references": [{ "path": "packages/a" }] }',
      'packages/a/tsconfig.json/keep': '',
    });
    expect(await tsconfigLeaves(directory)).toBe(true);
    expect(await tsconfigLeaves(looped)).toBe(true);
    expect(await tsconfigLeaves(referenced)).toBe(true);
  });

  it('reads past a missing reference and a probe that finds a directory', async () => {
    const dir = await component({
      'tsconfig.json': '{ "extends": "./configs/base", "references": [{ "path": "gone" }] }',
      'configs/base/keep': '',
      'configs/base.json': '{ "compilerOptions": {} }',
    });
    expect(await tsconfigLeaves(dir)).toBe(false);
  });

  const configDir = ['$', '{configDir}'].join('');

  it.each([
    ['an extends climbing out', `{ "extends": "${configDir}/../shared/tsconfig.json" }`],
    ['a reference climbing out', `{ "references": [{ "path": "${configDir}/../shared" }] }`],
    ['an extends staying inside', `{ "extends": "${configDir}/inner/tsconfig.json" }`],
    ['a reference staying inside', `{ "references": [{ "path": "${configDir}/inner" }] }`],
  ])('keeps the rewrite for a templated path: %s', async (_, tsconfig) => {
    const dir = await component({
      'tsconfig.json': tsconfig,
      'inner/tsconfig.json': '{ "compilerOptions": {} }',
      'shared/tsconfig.json': '{ "compilerOptions": {} }',
    });
    expect(await tsconfigLeaves(dir)).toBe(true);
  });
});
