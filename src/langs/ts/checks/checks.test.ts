describe('ts/size and ts/e2e', () => {
  it('reports budgets over their limit with the project’s size-limit', async () => {
    const yml = `${YML}size: .size-limit.json\n`;
    const ctx = await project(
      {
        '.size-limit.json': '[\n  { "name": "app", "path": "app.txt", "limit": "1 B" }\n]\n',
        'node_modules/size-limit/package.json': '{ "version": "14.1.0", "bin": "bin.js" }',
        'node_modules/size-limit/bin.js':
          'process.stdout.write(JSON.stringify([{ name: "app", passed: false, size: 2000, sizeLimit: 1 }]));\n',
      },
      { yml, modules: 'none' },
    );
    expect(await sizeCheck.run(ctx)).toEqual([
      {
        rule: 'size-limit/exceeded',
        message: 'app is 2.0 kB, over its 1 B budget.',
        key: 'size-limit app',
        location: { file: '.size-limit.json', line: 2 },
      },
    ]);
  });

  it('runs the Playwright suite and wants axe in it', async () => {
    const yml = `${YML}tests: { full: [e2e] }\n`;
    const report = [
      '<testsuites><testsuite name="a.spec.ts"><testcase name="works" classname="a.spec.ts">',
      '<failure message="a.spec.ts:3:1 works">Error: boom</failure></testcase></testsuite></testsuites>',
    ].join('');
    const ctx = await project(
      {
        'playwright.config.ts': 'export default {};\n',
        'e2e/a.spec.ts': "import { test } from '@playwright/test';\n\ntest('works', () => {});\n",
        'node_modules/@playwright/test/package.json':
          '{ "version": "1.56.1", "bin": { "playwright": "cli.js" } }',
        'node_modules/@playwright/test/cli.js': [
          "const { writeFileSync } = require('node:fs');",
          `writeFileSync(process.env.PLAYWRIGHT_JUNIT_OUTPUT_FILE, ${JSON.stringify(report)});`,
          'process.exitCode = 1;',
        ].join('\n'),
      },
      { yml, modules: 'none' },
    );
    expect(await e2eCheck.run(ctx)).toEqual([
      {
        rule: 'e2e/no-axe',
        message:
          'No file of the end-to-end suite in e2e uses @axe-core/playwright; check each screen with axe.',
        key: 'e2e/no-axe e2e',
        location: { file: 'playwright.config.ts', line: 1 },
      },
      {
        rule: 'playwright/failed',
        message: 'The end-to-end test "works" fails: Error: boom',
        location: { file: 'e2e/a.spec.ts', line: 3 },
      },
    ]);
  });

  it('is an engine error when the tool is not installed', async () => {
    const ctx = await project({}, { yml: `${YML}size: .size-limit.json\n`, modules: 'none' });
    await expect(sizeCheck.run(ctx)).rejects.toThrow(EngineError);
  });
});

describe('the Vitest and Stryker runners', () => {
  const files = {
    'talos.yml': YML,
    'src/clamp.ts':
      'export function clamp(x: number, max: number): number {\n  if (x > max) return max;\n  return x;\n}\n',
    'src/clamp.test.ts':
      "import { expect, it } from 'vitest';\nimport { clamp } from './clamp.js';\n\nit('clamps', () => {\n  expect(clamp(20, 10)).toBe(10);\n});\n",
    'vitest.project.ts':
      "import { defineConfig } from 'vitest/config';\n\nexport default defineConfig({ test: { include: ['src/**/*.test.ts'] } });\n",
  };

  it(
    'runs the tests with JUnit and LCOV, and a rerun of named files',
    { timeout: SLOW },
    async () => {
      const ctx = await project(files);
      const run = await vitestRunner.run(ctx, { suite: 'all', coverage: true });
      expect(run.exitCode).toBe(0);
      expect(await readFile(run.junit[0]?.path ?? '', 'utf8')).toContain('name="clamps"');
      expect(run.coverage?.format).toBe('lcov');
      expect(await readFile(run.coverage?.path ?? '', 'utf8')).toContain('SF:src/clamp.ts');
      const rerun = await vitestRunner.run(ctx, {
        suite: 'commit',
        coverage: false,
        files: ['src/clamp.test.ts'],
      });
      expect(rerun.junit).toHaveLength(1);
      expect(rerun.coverage).toBeUndefined();
    },
  );

  it('mutates the given files and reports every mutant', { timeout: SLOW }, async () => {
    const ctx = await project(files);
    const report = await strykerRunner.run(ctx, ['src/clamp.ts']);
    const json = JSON.parse(await readFile(report.path, 'utf8')) as {
      files: Record<string, { mutants: { status: string }[] }>;
    };
    expect(json.files['src/clamp.ts']?.mutants.map((m) => m.status)).toContain('Survived');
    const none = await strykerRunner.run(ctx, ['elsewhere/x.ts']);
    expect(JSON.parse(await readFile(none.path, 'utf8'))).toMatchObject({ files: {} });
  });
});
