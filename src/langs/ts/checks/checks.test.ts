/**
 * Each check run for real on a small project, with Talos's own installed tools (the versions it
 * pins) linked in as the project's node_modules.
 */

const TALOS_MODULES = join(process.cwd(), 'node_modules');
const YML = 'name: Test\nprefix: T\ncomponents: [{ lang: ts }]\n';
const SLOW = 120_000;

const PACKAGE = JSON.stringify({
  name: 'case',
  private: true,
  type: 'module',
  devDependencies: { vitest: '5.0.5' },
});

const TSCONFIG = JSON.stringify({
  extends: './tsconfig.talos.json',
  compilerOptions: {
    target: 'ES2023',
    lib: ['ES2023'],
    module: 'NodeNext',
    moduleResolution: 'NodeNext',
    types: ['node'],
    noEmit: true,
  },
  include: ['src', '*.config.ts', '*.project.ts'],
});

type Options = { readonly yml?: string; readonly modules?: 'talos' | 'none' };

async function project(
  files: Readonly<Record<string, string>>,
  options: Options = {},
): Promise<CheckContext> {
  const config = parseConfig(options.yml ?? YML);
  const component = config.components[0];
  if (component === undefined) throw new Error('the test project needs a component');
  const tracked = { 'package.json': PACKAGE, 'tsconfig.json': TSCONFIG, ...files };
  const root = await tempRepo(tracked);
  if ((options.modules ?? 'talos') === 'talos') {
    await symlink(TALOS_MODULES, join(root, 'node_modules'), 'dir');
  }
  const facts = repoFacts(Object.keys(tracked), config.exclude);
  for (const file of TS_GENERATED) {
    const render = { config, facts, version: '0.0.0-test', component };
    await writeFile(join(root, file.path), file.render(render));
    const extension = file.extension;
    if (extension !== undefined && !(extension.path in tracked)) {
      await writeFile(join(root, extension.path), extension.initial(render));
    }
  }
  const cache = new Map<string, Promise<unknown>>();
  return {
    root,
    sha: '0'.repeat(40),
    exec,
    tools: noTools,
    scratch: await mkdtemp(join(tmpdir(), 'talos-ts-')),
    log: silentLogger,
    os: 'linux',
    facts,
    config,
    component,
    side: 'alone',
    tiers: ['commit', 'head'],
    memo: <T>(key: string, compute: () => Promise<T>): Promise<T> => {
      const known = cache.get(key) ?? compute();
      cache.set(key, known);
      return known as Promise<T>;
    },
  };
}

async function rules(check: Check, ctx: CheckContext): Promise<string[]> {
  expect(check.applies(ctx)).toEqual({ applies: true });
  return [...new Set((await check.run(ctx)).map((finding) => finding.rule))].sort((a, b) =>
    a.localeCompare(b),
  );
}

describe('the TypeScript pack', () => {
  it('registers its checks, generated files, install and pinned tools', () => {
    expect(tsPack.checks.map((check) => check.id)).toContain('ts/config-strength');
    expect(tsPack.generated?.map((file) => file.path)).toContain('eslint.config.js');
    expect(tsPack.devTools?.packages).toHaveProperty('eslint');
    expect(tsPack).toHaveProperty('install');
  });
});

describe('ts/format', () => {
  it(
    'reports unformatted and unparsable files, never a rendered one',
    { timeout: SLOW },
    async () => {
      const ctx = await project({
        'src/a.ts': 'export const a = {b:1}\n',
        'src/ok.ts': "export const ok = 'yes';\n",
        'src/broken.ts': 'const x = (;\n',
        'eslint.config.js': '// Generated by Talos 0.0.0. Do not edit.\nexport default [ ]\n',
      });
      const findings = await formatCheck.run(ctx);
      const files = findings.map((finding) => finding.location?.file);
      expect(files).not.toContain('eslint.config.js');
      const inSource = findings.filter((finding) => finding.location?.file.startsWith('src/'));
      expect(inSource).toEqual([
        {
          rule: 'prettier/unformatted',
          message: 'src/a.ts is not formatted as Prettier formats it.',
          location: { file: 'src/a.ts', line: 1, endLine: 1 },
        },
        {
          rule: 'prettier/syntax-error',
          message: 'Prettier cannot parse this file: Expression expected.',
          location: { file: 'src/broken.ts', line: 1, column: 12 },
        },
      ]);
    },
  );
});

describe('ts/lint', () => {
  it('reports rules over the whole function and parse errors', { timeout: SLOW }, async () => {
    const branches = Array.from({ length: 13 }, (_, i) => `  if (x === ${i}) return ${i};`);
    const ctx = await project({
      'src/a.ts': [
        'export function f(x: number): number {',
        ...branches,
        '  return -1;',
        '}',
        '',
      ].join('\n'),
      'src/broken.ts': 'export const x = (;\n',
    });
    const findings = await lintCheck.run(ctx);
    expect(findings.find((f) => f.rule === 'eslint/complexity')?.location).toMatchObject({
      file: 'src/a.ts',
      line: 1,
      endLine: 16,
    });
    expect(findings.map((f) => f.rule)).toContain('eslint/parse-error');
  });
});

describe('ts/types and ts/typecov', () => {
  it('reports compiler errors and untyped identifiers', { timeout: SLOW }, async () => {
    const ctx = await project({
      'src/a.ts': "export const n: number = 'one';\nexport const m = [1][0]!;\n",
    });
    expect(await rules(typesCheck, ctx)).toEqual(['tsc/TS2322']);
    const untyped = await typecovCheck.run(ctx);
    expect(untyped).toMatchObject([
      { rule: 'typecov/untyped', location: { file: 'src/a.ts', line: 2 } },
    ]);
  });
});

describe('ts/deadcode', () => {
  it('reports unused files and exports', { timeout: SLOW }, async () => {
    const ctx = await project({
      'knip.project.json': '{ "entry": ["src/index.ts"], "project": ["src/**/*.ts"] }\n',
      'src/index.ts': "import { used } from './lib.js';\n\nexport const main = used;\n",
      'src/lib.ts': 'export const used = 1;\nexport const unused = 2;\n',
      'src/orphan.ts': 'export const orphan = 3;\n',
    });
    expect(await rules(deadcodeCheck, ctx)).toEqual(['knip/exports', 'knip/files']);
  });
});

describe('ts/javascript', () => {
  it('reports JavaScript sources', async () => {
    const ctx = await project({ 'src/old.js': 'export const old = 1;\n' }, { modules: 'none' });
    expect(await rules(javascriptCheck, ctx)).toEqual(['ts/javascript']);
  });
});

describe('ts/arch', () => {
  it('reports cycles and dev dependencies in shipped code', { timeout: SLOW }, async () => {
    const ctx = await project({
      'src/a.ts': "import { b } from './b.js';\n\nexport const a = (): number => b() + 1;\n",
      'src/b.ts': "import { a } from './a.js';\n\nexport const b = (): number => (a ? 1 : 0);\n",
      'src/c.ts': "import { describe } from 'vitest';\n\nexport const c = describe;\n",
    });
    expect(await rules(archCheck, ctx)).toEqual([
      'depcruise/no-circular',
      'depcruise/no-dev-deps-in-shipped-code',
    ]);
  });
});

describe('ts/config-strength', () => {
  it('passes the rendered base with its first extension files', { timeout: SLOW }, async () => {
    const ctx = await project({ 'src/a.ts': 'export const a = 1;\n' });
    expect(await strengthCheck.run(ctx)).toEqual([]);
  });

  it('reports what the project weakens or shadows', { timeout: SLOW }, async () => {
    const ctx = await project({
      'src/a.ts': 'export const a = 1;\n',
      'src/skip.ts': 'export const skip = 1;\n',
      'eslint.project.js':
        "export default { ignores: ['src/skip.ts'], configs: [{ rules: { 'max-depth': 'off' } }] };\n",
      'knip.project.json': '{ "exclude": ["exports"] }\n',
      '.prettierrc': '{}\n',
      'package.json': JSON.stringify({ name: 'case', type: 'module', prettier: {} }),
    });
    const findings = await strengthCheck.run(ctx);
    expect(findings.map((f) => f.key ?? '').sort((a, b) => a.localeCompare(b))).toEqual([
      'eslint ignores src/skip.ts',
      'eslint max-depth/off',
      'knip exclude',
      'shadowed .prettierrc',
      'shadowed package.json#prettier',
    ]);
  });
});

