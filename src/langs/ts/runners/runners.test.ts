import { mkdir, mkdtemp, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';
import { strykerTargets, strykerWrapper, tsconfigLeaves } from './stryker.js';
import { vitestArgs } from './vitest.js';

describe('vitestArgs', () => {
  it('runs with JUnit and LCOV into scratch, leaving the excluded directories out', () => {
    expect(
      vitestArgs({
        junit: '/s/junit.xml',
        coverageDir: '/s/coverage',
        excluded: ['e2e', 'test/db'],
        coverage: true,
      }),
    ).toEqual([
      'run',
      '--reporter=junit',
      '--outputFile=/s/junit.xml',
      '--passWithNoTests',
      '--allowOnly=false',
      '--exclude',
      'e2e/**',
      '--exclude',
      'test/db/**',
      '--coverage.enabled',
      '--coverage.provider=v8',
      '--coverage.reporter=lcovonly',
      '--coverage.reportsDirectory=/s/coverage',
      '--coverage.reportOnFailure',
      '--coverage.thresholds=false',
    ]);
  });

  it('switches the project’s coverage thresholds off on a rerun with coverage too', () => {
    const args = vitestArgs({
      junit: '/s/j.xml',
      coverageDir: '/s/c',
      excluded: [],
      coverage: true,
      files: ['src/a.test.ts'],
    });
    expect(args.slice(-2)).toEqual(['--coverage.thresholds=false', 'src/a.test.ts']);
  });

  it('switches coverage off and names the files of a rerun', () => {
    const args = vitestArgs({
      junit: '/s/j.xml',
      coverageDir: '/s/c',
      excluded: [],
      coverage: false,
      files: ['src/a.test.ts'],
    });
    expect(args.slice(-2)).toEqual(['--coverage.enabled=false', 'src/a.test.ts']);
  });
});

describe('strykerWrapper', () => {
  it('narrows the base to the files and writes only the JSON report', () => {
    const text = strykerWrapper('file:///r/stryker.config.mjs', ['src/a.ts'], '/s/mutation.json');
    expect(text).toContain('import base from "file:///r/stryker.config.mjs";');
    expect(text).toContain('mutate: ["src/a.ts"],');
    expect(text).toContain("reporters: ['json'],");
    expect(text).toContain('jsonReporter: { fileName: "/s/mutation.json" },');
  });

  it('disables type checks in the mutated files alone, unless the base never does', () => {
    const one = strykerWrapper('file:///r/s.mjs', ['src/a.ts'], '/s/m.json');
    expect(one).toContain(
      'disableTypeChecks: base.disableTypeChecks === false ? false : "src/a.ts",',
    );
    const two = strykerWrapper('file:///r/s.mjs', ['src/a.ts', 'src/b.ts'], '/s/m.json');
    expect(two).toContain('false : "{src/a.ts,src/b.ts}",');
  });

  it("points Stryker at no tsconfig only when asked, keeping the base's own", () => {
    expect(strykerWrapper('file:///r/s.mjs', ['a.ts'], '/s/m.json')).not.toContain('tsconfigFile');
    const text = strykerWrapper('file:///r/s.mjs', ['a.ts'], '/s/m.json', {
      noTsconfig: '/s/no-tsconfig.json',
    });
    expect(text).toContain('tsconfigFile: base.tsconfigFile ?? "/s/no-tsconfig.json",');
  });
});

describe('tsconfigLeaves', () => {
  async function component(files: Record<string, string>): Promise<string> {
    const dir = await mkdtemp(join(tmpdir(), 'tsconfig-leaves-'));
    for (const [name, text] of Object.entries(files)) {
      await mkdir(join(dir, name, '..'), { recursive: true });
      await writeFile(join(dir, name), text);
    }
    return dir;
  }

  it('stays inside a chain of relative tsconfigs that name nothing outside', async () => {
    const dir = await component({
      'tsconfig.json':
        '{\n  // ours\n  "extends": "./tsconfig.talos.json",\n  "include": ["src"]\n}',
      'tsconfig.talos.json':
        '{ "//": "Generated by Talos.", "compilerOptions": { "strict": true } }',
    });
    expect(await tsconfigLeaves(dir)).toBe(false);
    expect(await tsconfigLeaves(join(dir, 'none'))).toBe(false);
  });

  it('leaves through an extended file, a reference or an absolute path', async () => {
    const extended = await component({
      'tsconfig.json': '{ "extends": "./configs/base" }',
      'configs/base.json': '{ "include": ["../../shared/**"] }',
    });
    const referenced = await component({
      'tsconfig.json': '{ "references": [{ "path": "./packages/a" }] }',
      'packages/a/tsconfig.json': '{ "extends": "../../../tsconfig.base.json" }',
    });
    const absolute = await component({ 'tsconfig.json': '{ "files": ["/opt/types.d.ts"] }' });
    expect(await tsconfigLeaves(extended)).toBe(true);
    expect(await tsconfigLeaves(referenced)).toBe(true);
    expect(await tsconfigLeaves(absolute)).toBe(true);
  });

  it.each([
    ['a bare directory', 'packages/a', 'packages/a/tsconfig.json'],
    ['a dotted directory', './packages/a', 'packages/a/tsconfig.json'],
    ['a bare file', 'packages/a/tsconfig.app.json', 'packages/a/tsconfig.app.json'],
  ])('follows a reference to %s into what it extends', async (_, path, target) => {
    const outside = await component({
      'tsconfig.json': `{ "references": [{ "path": "${path}" }], }`,
      [target]: '{ "extends": "../../../tsconfig.base.json" }',
    });
    const inside = await component({
      'tsconfig.json': `{ "references": [{ "path": "${path}" }] }`,
      [target]: '{ "extends": "../../tsconfig.base.json" }',
      'tsconfig.base.json': '{ /* shared */ "compilerOptions": {} }',
    });
    expect(await tsconfigLeaves(outside)).toBe(true);
    expect(await tsconfigLeaves(inside)).toBe(false);
  });

  it('follows each relative base of an extends list, and no package', async () => {
    const dir = await component({
      'tsconfig.json': '{ "extends": ["@tsconfig/node22/tsconfig.json", "./configs/strict"] }',
      'configs/strict.json': '{ "extends": "../../outer.json" }',
    });
    const packaged = await component({
      'tsconfig.json': '{ "extends": "@tsconfig/node22/tsconfig.json" }',
    });
    expect(await tsconfigLeaves(dir)).toBe(true);
    expect(await tsconfigLeaves(packaged)).toBe(false);
  });

  it("keeps Stryker's rewrite for a tsconfig it can't read", async () => {
    const dir = await component({ 'tsconfig.json': '{ "extends": ' });
    const shape = await component({ 'tsconfig.json': '{ "references": "packages/a" }' });
    expect(await tsconfigLeaves(dir)).toBe(true);
    expect(await tsconfigLeaves(shape)).toBe(true);
  });
});

describe('strykerTargets', () => {
  it("mutates the component's present files, never one this pack renders", async () => {
    const repo = await mkdtemp(join(tmpdir(), 'stryker-targets-'));
    const dir = join(repo, 'web');
    await mkdir(join(dir, 'src/configs'), { recursive: true });
    await writeFile(join(dir, 'src/a.ts'), 'export const a = 1;\n');
    await writeFile(join(dir, 'eslint.config.js'), 'export default [];\n');
    await writeFile(join(dir, 'vitest.config.ts'), 'export default {};\n');
    await writeFile(
      join(dir, 'src/configs/header.ts'),
      "export const GENERATED_MARKER = 'Generated by Talos';\n",
    );
    await writeFile(join(repo, 'other.ts'), 'export const o = 1;\n');
    const files = [
      'web/src/a.ts',
      'web/src/gone.ts',
      'web/eslint.config.js',
      'web/vitest.config.ts',
      'web/src/configs/header.ts',
      'other.ts',
    ];
    expect(await strykerTargets(repo, 'web', files)).toEqual(['src/a.ts', 'src/configs/header.ts']);
  });
});
