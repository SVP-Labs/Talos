import { mkdir, mkdtemp, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { describe, expect, it } from 'vitest';
import { strykerTargets, strykerWrapper } from './stryker.js';
import { vitestArgs } from './vitest.js';

describe('vitestArgs', () => {
  it('runs with JUnit and LCOV into scratch, leaving the excluded directories out', () => {
    expect(
      vitestArgs({
        junit: '/s/junit.xml',
        coverageDir: '/s/coverage',
        excluded: ['e2e', 'test/db'],
        coverage: true,
      }),
    ).toEqual([
      'run',
      '--reporter=junit',
      '--outputFile=/s/junit.xml',
      '--passWithNoTests',
      '--allowOnly=false',
      '--exclude',
      'e2e/**',
      '--exclude',
      'test/db/**',
      '--coverage.enabled',
      '--coverage.provider=v8',
      '--coverage.reporter=lcovonly',
      '--coverage.reportsDirectory=/s/coverage',
      '--coverage.reportOnFailure',
      '--coverage.thresholds=false',
    ]);
  });

  it('switches the project’s coverage thresholds off on a rerun with coverage too', () => {
    const args = vitestArgs({
      junit: '/s/j.xml',
      coverageDir: '/s/c',
      excluded: [],
      coverage: true,
      files: ['src/a.test.ts'],
    });
    expect(args.slice(-2)).toEqual(['--coverage.thresholds=false', 'src/a.test.ts']);
  });

  it('switches coverage off and names the files of a rerun', () => {
    const args = vitestArgs({
      junit: '/s/j.xml',
      coverageDir: '/s/c',
      excluded: [],
      coverage: false,
      files: ['src/a.test.ts'],
    });
    expect(args.slice(-2)).toEqual(['--coverage.enabled=false', 'src/a.test.ts']);
  });
});

describe('strykerWrapper', () => {
  it('narrows the base to the files and writes only the JSON report', () => {
    const text = strykerWrapper('file:///r/stryker.config.mjs', ['src/a.ts'], '/s/mutation.json');
    expect(text).toContain('import base from "file:///r/stryker.config.mjs";');
    expect(text).toContain('mutate: ["src/a.ts"],');
    expect(text).toContain("reporters: ['json'],");
    expect(text).toContain('jsonReporter: { fileName: "/s/mutation.json" },');
  });

  it('disables type checks in the mutated files alone, unless the base never does', () => {
    const one = strykerWrapper('file:///r/s.mjs', ['src/a.ts'], '/s/m.json');
    expect(one).toContain(
      'disableTypeChecks: base.disableTypeChecks === false ? false : "src/a.ts",',
    );
    const two = strykerWrapper('file:///r/s.mjs', ['src/a.ts', 'src/b.ts'], '/s/m.json');
    expect(two).toContain('false : "{src/a.ts,src/b.ts}",');
  });

  const wrapped = {
    mutate: ['a.ts'],
    disableTypeChecks: 'a.ts',
    reporters: ['json'],
    jsonReporter: { fileName: '/s/m.json' },
    incremental: false,
  };

  it.each([
    ['a plain base', {}, { tsconfigFile: '/s/none.json' }],
    ['a base with its own tsconfig', { tsconfigFile: 'app.json' }, { tsconfigFile: 'app.json' }],
    ['a base running the TypeScript checker', { checkers: ['typescript'] }, {}],
  ])('points Stryker at no tsconfig for %s only if it may', async (_, base, tsconfig) => {
    const dir = await mkdtemp(join(tmpdir(), 'stryker-wrapper-'));
    await writeFile(join(dir, 'base.mjs'), `export default ${JSON.stringify(base)};\n`);
    const wrapper = join(dir, 'wrapper.mjs');
    const url = pathToFileURL(join(dir, 'base.mjs')).href;
    await writeFile(
      wrapper,
      strykerWrapper(url, ['a.ts'], '/s/m.json', { noTsconfig: '/s/none.json' }),
    );
    const loaded: unknown = await import(pathToFileURL(wrapper).href);
    expect(loaded).toHaveProperty('default', { ...base, ...tsconfig, ...wrapped });
  });

  it('leaves the tsconfig setting alone unless asked', () => {
    expect(strykerWrapper('file:///r/s.mjs', ['a.ts'], '/s/m.json')).not.toContain('tsconfigFile');
  });
});

describe('strykerTargets', () => {
  it("mutates the component's present files, never one this pack renders", async () => {
    const repo = await mkdtemp(join(tmpdir(), 'stryker-targets-'));
    const dir = join(repo, 'web');
    await mkdir(join(dir, 'src/configs'), { recursive: true });
    await writeFile(join(dir, 'src/a.ts'), 'export const a = 1;\n');
    await writeFile(join(dir, 'eslint.config.js'), 'export default [];\n');
    await writeFile(join(dir, 'vitest.config.ts'), 'export default {};\n');
    await writeFile(
      join(dir, 'src/configs/header.ts'),
      "export const GENERATED_MARKER = 'Generated by Talos';\n",
    );
    await writeFile(join(repo, 'other.ts'), 'export const o = 1;\n');
    const files = [
      'web/src/a.ts',
      'web/src/gone.ts',
      'web/eslint.config.js',
      'web/vitest.config.ts',
      'web/src/configs/header.ts',
      'other.ts',
    ];
    expect(await strykerTargets(repo, 'web', files)).toEqual(['src/a.ts', 'src/configs/header.ts']);
  });
});
