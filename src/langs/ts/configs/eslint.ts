/**
 * ESLint's base: typescript-eslint's strict and stylistic type-checked rules, SonarJS's
 * recommended rules, a curated part of unicorn, and the size and complexity limits. The
 * project's file adds ignores, files linted without a tsconfig, and further config objects.
 */
export function renderEslint(ctx: RenderContext): string {
  const ignores = [...IGNORED, ...excludes(ctx).flatMap((entry) => excludeGlobs(entry))];
  return `${generatedHeader('//', ctx.version, ESLINT_PROJECT)}import js from '@eslint/js';
import comments from '@eslint-community/eslint-plugin-eslint-comments/configs';
import stylistic from '@stylistic/eslint-plugin';
import { defineConfig } from 'eslint/config';
import importX from 'eslint-plugin-import-x';
import sonarjs from 'eslint-plugin-sonarjs';
import unicorn from 'eslint-plugin-unicorn';
import globals from 'globals';
import tseslint from 'typescript-eslint';
import project from './${ESLINT_PROJECT}';

${RULES}
${configs(ignores)}`;
}

export function eslintProjectInitial(): string {
  return `// The project's additions to the generated ESLint base (${ESLINT_BASE}).
export default {
  /** Paths ESLint skips beyond talos.yml's exclude. */
  ignores: [],
  /** TypeScript files no tsconfig includes, linted with a default project. */
  defaultProject: [],
  /** Further config objects, applied after the base. */
  configs: [],
};
`;
}
