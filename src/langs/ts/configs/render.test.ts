import { readFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import { EXTENSION_PATHS, GENERATED_PATHS, TS_GENERATED } from './index.js';
import { mutateGlobs } from './stryker.js';
import { parseConfig } from '../../../config/load.js';
import type { RenderContext } from '../../../core/pack.js';
import { repoFacts } from '../../../repo/facts.js';
import { ownVersion } from '../../../version/self.js';

const repo = new URL('../../../../', import.meta.url);

function read(path: string): string {
  return readFileSync(new URL(path, repo), 'utf8');
}

function context(talosYml: string, version = ownVersion()): RenderContext {
  const config = parseConfig(talosYml);
  const component = config.components.find((c) => c.lang === 'ts');
  return {
    config,
    facts: repoFacts([], config.exclude),
    version,
    ...(component === undefined ? {} : { component }),
  };
}

describe("Talos's own tool configs", () => {
  const ctx = context(read('talos.yml'));

  it.each(TS_GENERATED.map((file) => file.path))('%s is exactly what the pack renders', (path) => {
    const file = TS_GENERATED.find((g) => g.path === path);
    expect(file?.render(ctx)).toBe(read(path));
  });

  it("keeps Talos's additions in the extension files, which exist", () => {
    for (const path of EXTENSION_PATHS) expect(read(path).length).toBeGreaterThan(0);
    expect(read('knip.project.json')).toContain('src/bin/talos.ts');
    expect(read('vitest.project.ts')).toContain('src/**/*.test.ts');
  });
});

describe('rendering for a component', () => {
  const yml = [
    'name: Demo',
    'prefix: D',
    'components:',
    '  - { lang: ts, root: apps/web }',
    'exclude: [apps/web/generated, vendor, apps/web/src/*.gen.ts]',
    'mutation: [apps/web/src/risk, apps/web/src/gate.ts, packages/other/x.ts]',
  ].join('\n');
  const ctx = context(yml, '9.9.9');
  const render = (path: string): string =>
    TS_GENERATED.find((g) => g.path === path)?.render(ctx) ?? '';

  it('starts every file with the generated header naming its extension', () => {
    expect(render('eslint.config.js').split('\n')[0]).toBe(
      '// Generated by Talos 9.9.9. Do not edit: extend it in eslint.project.js, which may only tighten it.',
    );
    expect(JSON.parse(render('tsconfig.talos.json'))).toMatchObject({
      '//': 'Generated by Talos 9.9.9. Do not edit: extend it in tsconfig.json, which may only tighten it.',
      compilerOptions: { strict: true, exactOptionalPropertyTypes: true, checkJs: true },
    });
    expect(render('.prettierignore').split('\n')[0]).toBe(
      '# Generated by Talos 9.9.9. Do not edit.',
    );
  });

  it("keeps only the component's excludes, relative to its root", () => {
    expect(render('eslint.config.js')).toContain("'generated/**',");
    expect(render('eslint.config.js')).toContain("'src/*.gen.ts',");
    expect(render('eslint.config.js')).not.toContain('vendor');
    expect(render('.prettierignore')).toContain('/generated\n');
    expect(render('.dependency-cruiser.cjs')).toContain(
      String.raw`^generated(/|$)|^src/[^/]*\.gen\.ts(/|$)`,
    );
    expect(render('knip.config.js')).toContain("'generated/**',");
    expect(render('vitest.config.ts')).toContain("'generated/**',");
  });

  it("mutates the component's mutation paths, files as they are and directories by glob", () => {
    expect(mutateGlobs(ctx)).toEqual([
      'src/gate.ts',
      'src/risk/**/*.{ts,tsx,mts,cts,js,jsx,mjs,cjs}',
      '!**/*.{test,spec}.*',
    ]);
    expect(render('stryker.config.mjs')).toContain("'src/gate.ts',");
  });

  it('leaves mutate to Stryker when talos.yml names no path', () => {
    const plain = context('name: P\nprefix: P\ncomponents: [{ lang: ts }]\n');
    const stryker = TS_GENERATED.find((g) => g.path === 'stryker.config.mjs');
    expect(stryker?.render(plain)).not.toContain('mutate');
  });

  it('lists every rendered file in the Prettier ignore file', () => {
    const ignore = render('.prettierignore');
    for (const path of GENERATED_PATHS) expect(ignore).toContain(`/${path}\n`);
  });

  it('gives each extension file a first version that the base can import', () => {
    for (const { extension } of TS_GENERATED) {
      const initial = extension?.initial(ctx) ?? '';
      const parses = (): unknown => JSON.parse(initial);
      if (extension === undefined) continue;
      if (extension.path.endsWith('.json')) {
        expect(parses).not.toThrow();
      } else {
        expect(initial).toMatch(/export default|module\.exports/);
      }
    }
  });
});
