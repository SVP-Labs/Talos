import { describe, expect, it } from 'vitest';
import { deptracBase, phpmdBase, phpstanBase, PHP_GENERATED, pintBase } from './configs.js';
import { DEPTRAC_BASE, renderDeptracBase } from './deptrac-config.js';
import { renderPhpmd } from './phpmd-config.js';
import { extensionsFor, renderPhpstanBase } from './phpstan-config.js';
import { renderPint } from './pint-config.js';
import { parseConfig } from '../../config/load.js';
import type { RenderContext } from '../../core/pack.js';
import { repoFacts } from '../../repo/facts.js';

function render(files: string[], exclude: string[] = []): RenderContext {
  const config = parseConfig(
    `name: T\nprefix: T\ncomponents:\n  - { lang: php, root: app }\nexclude: [${exclude.join(', ')}]\n`,
  );
  return {
    config,
    facts: repoFacts(files, config.exclude),
    component: { lang: 'php', root: 'app', os: ['linux'] },
    version: '1.2.3',
  };
}

describe('the PHPStan base', () => {
  it('includes each extension, then the project file, and sets the strict switches', () => {
    const text = renderPhpstanBase('1.2.3', false);
    expect(text.split('\n')[0]).toBe(
      '# Generated by Talos 1.2.3. Do not edit: extend it in phpstan.project.neon, which may only tighten it.',
    );
    expect(text).toContain('    - "vendor/phpstan/phpstan-strict-rules/rules.neon"\n');
    expect(text).toContain('    - "phpstan.project.neon"\nparameters:\n    level: "max"\n');
    expect(text).toContain('    cognitive_complexity:\n        function: 15\n');
    expect(text).not.toContain('larastan');
  });

  it('includes Larastan in a Laravel application, which tracks artisan', () => {
    expect(extensionsFor(true).map((e) => e.pkg)).toContain('larastan/larastan');
    expect(phpstanBase.render(render(['app/artisan', 'app/src/A.php']))).toContain(
      'vendor/larastan/larastan/extension.neon',
    );
    expect(phpstanBase.render(render(['app/src/A.php']))).not.toContain('larastan');
  });

  it("writes the project's file with the directories its PHP is in", () => {
    const initial = phpstanBase.extension?.initial(
      render(['app/src/A.php', 'app/tests/ATest.php', 'app/index.php']),
    );
    expect(initial).toBe(
      "# This project's additions to phpstan.neon, which may only tighten it.\n" +
        'parameters:\n    paths:\n        - "src"\n        - "tests"\n        - "index.php"\n',
    );
  });
});

describe('the PHPMD base', () => {
  it('sets the standard limits and references the project ruleset', () => {
    const text = phpmdBase.render(render(['app/src/A.php']));
    expect(
      text.startsWith('<!-- Generated by Talos 1.2.3. Do not edit: extend it in phpmd.project.xml'),
    ).toBe(true);
    expect(text).toContain('<exclude name="StaticAccess"/>');
    expect(text).toContain(
      '    <rule ref="rulesets/codesize.xml/CyclomaticComplexity">\n        <properties>\n' +
        '            <property name="maximum" value="12"/>',
    );
    expect(text).toContain('<property name="maximum" value="4"/>');
    expect(text).toContain('<property name="ignore-whitespace" value="true"/>');
    expect(text).toContain('    <rule ref="phpmd.project.xml"/>\n</ruleset>\n');
  });

  it("gives the gate's copy the project ruleset by path, escaped, or none", () => {
    expect(renderPhpmd('', '/a&b/phpmd.project.xml')).toContain(
      '<rule ref="/a&amp;b/phpmd.project.xml"/>',
    );
    expect(renderPhpmd('', undefined)).not.toContain('project');
  });
});

describe('the pint config', () => {
  it("is Laravel's preset with strict types, and talos.yml's exclusions", () => {
    expect(JSON.parse(pintBase.render(render(['app/src/A.php'], ['app/legacy', 'docs'])))).toEqual({
      '//': 'Generated by Talos 1.2.3. Do not edit.',
      preset: 'laravel',
      rules: { declare_strict_types: true },
      notPath: ['legacy'],
    });
    expect(JSON.parse(renderPint(''))).toEqual({
      preset: 'laravel',
      rules: { declare_strict_types: true },
    });
  });
});

describe('the deptrac base', () => {
  it('holds the universal layers and says where the project rules go', () => {
    const text = renderDeptracBase('1.2.3');
    expect(text).toContain('# Generated by Talos 1.2.3. Do not edit.\n');
    expect(text).toContain('deptrac.project.yaml');
    expect(text).toContain('    - name: Tests\n');
    expect(text).toContain('  ruleset:\n    Tests:\n      - Shipped\n');
    expect(deptracBase.path).toBe(DEPTRAC_BASE);
  });
});

describe('PHP_GENERATED', () => {
  it('renders four bases per PHP component, where it has PHP', () => {
    expect(PHP_GENERATED.map((g) => g.path)).toEqual([
      'phpstan.neon',
      'phpmd.xml',
      'pint.json',
      'deptrac.yaml',
    ]);
    const apply = {
      config: parseConfig('name: T\nprefix: T\n'),
      side: 'alone' as const,
      tiers: [],
    };
    const component = { lang: 'php' as const, root: 'app', os: ['linux' as const] };
    expect(phpstanBase.applies({ ...apply, facts: repoFacts(['app/a.php'], []), component })).toBe(
      true,
    );
    expect(
      phpstanBase.applies({ ...apply, facts: repoFacts(['app/a.blade.php'], []), component }),
    ).toBe(false);
  });
});
