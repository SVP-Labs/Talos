import { format } from 'prettier';
import { describe, expect, it } from 'vitest';
import { comparedFiles } from './code-files.js';
import { excludeGlobs, gateSettings, renderJscpdBase } from './jscpd-config.js';
import { PRETTIER_OPTIONS } from '../../langs/ts/configs/prettier.js';
import { repoFacts } from '../../repo/facts.js';

describe('the jscpd base', () => {
  it('carries the thresholds, every language, the tests and the exclude', () => {
    const text = renderJscpdBase('1.0.0', ['vendor/', 'app']);
    const parsed: unknown = JSON.parse(text);
    expect(parsed).toMatchObject({
      '//': 'Generated by Talos 1.0.0. Do not edit.',
      minTokens: 50,
      minLines: 5,
      threshold: 0,
    });
    expect(text).toContain('"typescript"');
    expect(text).toContain('"**/test_*.py"');
    expect(text).toContain('"vendor/**"');
    expect(text).toContain('"app/**"');
  });

  it('is written as Prettier writes it', async () => {
    const text = renderJscpdBase('1.0.0', ['generated/code']);
    expect(await format(text, { ...PRETTIER_OPTIONS, parser: 'json' })).toBe(text);
  });

  it('gives the gate the thresholds alone', () => {
    expect(JSON.parse(gateSettings())).toEqual({ minTokens: 50, minLines: 5 });
  });

  it('turns exclude entries into globs', () => {
    expect(excludeGlobs(['a/', 'b'])).toEqual(['a', 'a/**', 'b', 'b/**']);
  });
});

describe('comparedFiles', () => {
  it('takes every language and leaves tests, templates and the exclude out', () => {
    const facts = repoFacts(
      [
        'src/a.ts',
        'src/a.test.ts',
        'app/models.py',
        'app/test_models.py',
        'tests/conftest.py',
        'lib/x.lua',
        'spec/x_spec.lua',
        'src/main.rs',
        'tests/it.rs',
        'src/Thing.php',
        'tests/ThingTest.php',
        'resources/views/home.blade.php',
        'scripts/run.sh',
        'tools/build.ps1',
        'README.md',
        'config.yml',
        'vendored/lib.js',
      ],
      ['vendored'],
    );
    expect(comparedFiles(facts)).toEqual([
      'src/a.ts',
      'app/models.py',
      'lib/x.lua',
      'src/main.rs',
      'src/Thing.php',
      'scripts/run.sh',
      'tools/build.ps1',
    ]);
  });
});
