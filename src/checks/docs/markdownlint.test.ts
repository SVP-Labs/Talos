import { lint } from 'markdownlint-cli2/markdownlint/promise';
import { format } from 'prettier';
import { describe, expect, it } from 'vitest';
import { parse } from 'yaml';
import {
  excludeGlobs,
  MARKDOWNLINT_RULES,
  markdownlintFindings,
  renderMarkdownlintBase,
} from './markdownlint.js';
import { EngineError } from '../../core/check.js';

const PRETTIER = { printWidth: 100, singleQuote: true, trailingComma: 'all' } as const;

/** What markdownlint 0.41 returned for a heading after the title, recorded. */
const RECORDED = {
  'docs/a.md': [
    {
      lineNumber: 3,
      ruleNames: ['MD025', 'single-title', 'single-h1'],
      ruleDescription: 'Multiple top-level headings in the same document',
      ruleInformation: 'https://github.com/DavidAnson/markdownlint/blob/v0.41.1/doc/md025.md',
      errorDetail: null,
      errorContext: 'Two',
      errorRange: null,
      fixInfo: null,
      severity: 'error',
    },
    {
      lineNumber: 5,
      ruleNames: ['MD013', 'line-length'],
      ruleDescription: 'Line length',
      ruleInformation: 'https://github.com/DavidAnson/markdownlint/blob/v0.41.1/doc/md013.md',
      errorDetail: 'Expected: 100; Actual: 120',
      errorContext: null,
      errorRange: [101, 20],
      fixInfo: null,
      severity: 'error',
    },
  ],
};

describe('renderMarkdownlintBase', () => {
  const text = renderMarkdownlintBase('1.2.3', ['vendor/', 'app']);

  it('starts with the generated header and ignores what talos.yml excludes', () => {
    expect(text.split('\n')[0]).toBe('// Generated by Talos 1.2.3. Do not edit.');
    const config: unknown = parse(text.split('\n').slice(2).join('\n'));
    expect(config).toEqual({
      config: MARKDOWNLINT_RULES,
      globs: ['**/*.md'],
      ignores: [
        '**/node_modules/**',
        '**/pull_request_template.md',
        'vendor',
        'vendor/**',
        'app',
        'app/**',
      ],
      gitignore: true,
      noInlineConfig: true,
    });
  });

  it('is already formatted as Prettier formats it, long lists included', async () => {
    expect(await format(text, { ...PRETTIER, parser: 'jsonc' })).toBe(text);
    const long = renderMarkdownlintBase('1.2.3', [
      'a/very/long/directory/name',
      'another/one/here',
    ]);
    expect(await format(long, { ...PRETTIER, parser: 'jsonc' })).toBe(long);
  });

  it('turns each exclude entry into a file and a directory glob', () => {
    expect(excludeGlobs(['a/', 'b/c'])).toEqual(['a', 'a/**', 'b/c', 'b/c/**']);
  });
});

describe('markdownlintFindings', () => {
  it('turns recorded results into findings', () => {
    expect(markdownlintFindings(RECORDED)).toEqual([
      {
        rule: 'markdownlint/MD025',
        message: 'Multiple top-level headings in the same document.',
        location: { file: 'docs/a.md', line: 3 },
      },
      {
        rule: 'markdownlint/MD013',
        message: 'Line length (Expected: 100; Actual: 120).',
        location: { file: 'docs/a.md', line: 5, column: 101 },
      },
    ]);
  });

  it('reads what the library returns for the base rules', async () => {
    const long = `${'word '.repeat(25)}end`;
    const results = await lint({
      strings: { 'a.md': `# T\n\n<!-- markdownlint-disable -->\n${long}\n\n| ${long} |\n| - |\n` },
      config: MARKDOWNLINT_RULES,
      noInlineConfig: true,
      handleRuleFailures: true,
    });
    expect(markdownlintFindings(results).map((f) => [f.rule, f.location?.line])).toEqual([
      ['markdownlint/MD013', 4],
    ]);
  });

  it('refuses results it cannot read', () => {
    expect(() => markdownlintFindings({ 'a.md': [{ lineNumber: 'x' }] })).toThrow(EngineError);
  });
});
