import { format } from 'prettier';
import { describe, expect, it } from 'vitest';
import { parse } from 'yaml';
import {
  gateSettings,
  IGNORED_PATTERNS,
  KIT_WORDS,
  renderCspellBase,
  spellingFiles,
  spellingFinding,
} from './cspell.js';
import { EngineError } from '../../core/check.js';
import { repoFacts } from '../../repo/facts.js';

describe('renderCspellBase', () => {
  const text = renderCspellBase('1.2.3', ['vendor']);

  it("imports the project's word list and ignores what talos.yml excludes", () => {
    expect(text.split('\n')[0]).toBe('# Generated by Talos 1.2.3. Do not edit.');
    expect(parse(text)).toEqual({
      version: '0.2',
      language: 'en,en-GB',
      dictionaryDefinitions: [{ name: 'project', path: './.cspell/words.txt', addWords: true }],
      dictionaries: ['project'],
      words: KIT_WORDS,
      ignoreRegExpList: IGNORED_PATTERNS,
      ignorePaths: [
        '**/node_modules/**',
        '.cspell/**',
        '**/pnpm-lock.yaml',
        '**/*.lock',
        'vendor',
        'vendor/**',
      ],
    });
  });

  it('is already formatted as Prettier formats it', async () => {
    const options = { printWidth: 100, singleQuote: true, parser: 'yaml' } as const;
    expect(await format(text, options)).toBe(text);
  });

  it("hides Talos's block in CLAUDE.md, whatever it holds", () => {
    const pattern = IGNORED_PATTERNS[0] ?? '';
    const regex = new RegExp(pattern.slice(1, -2), 'g');
    const text = 'a\n<!-- talos:begin -->\nhidden\n<!-- talos:end -->\nb';
    expect(text.replaceAll(regex, '')).toBe('a\n\nb');
  });
});

describe('gateSettings', () => {
  it("adds the glossary's dictionary, and the word list only when there is one", () => {
    const settings = gateSettings({ glossary: '/s/glossary.txt' });
    expect(settings).toMatchObject({
      dictionaryDefinitions: [{ name: 'glossary', path: '/s/glossary.txt' }],
      dictionaries: ['glossary'],
      noConfigSearch: true,
    });
    expect(gateSettings({ glossary: '/g', words: '/w' })).toMatchObject({
      dictionaries: ['project', 'glossary'],
    });
  });
});

describe('spellingFiles', () => {
  it('reads docs, code, scripts and CI, not lock files', () => {
    const facts = repoFacts(
      [
        'README.md',
        'src/a.ts',
        'scripts/x.sh',
        '.github/workflows/ci.yml',
        'pnpm-lock.yaml',
        'Cargo.lock',
        'logo.png',
        'Dockerfile',
        'vendor/v.ts',
      ],
      ['vendor'],
    );
    expect(spellingFiles(facts)).toEqual([
      'README.md',
      'src/a.ts',
      'scripts/x.sh',
      '.github/workflows/ci.yml',
      'Dockerfile',
    ]);
  });
});

describe('spellingFinding', () => {
  const word = ['spe', 'ling'].join('');

  it('turns a recorded cspell issue into a finding', () => {
    const issue = {
      text: word,
      offset: 16,
      line: { text: `const x = 1; // ${word}\n`, offset: 0 },
      length: 7,
      isFlagged: false,
      isFound: false,
      row: 1,
      col: 17,
      uri: 'file:///repo/src/b.ts',
      context: { text: `// ${word}`, offset: 13 },
    };
    expect(spellingFinding('/repo', issue)).toEqual({
      rule: 'cspell/unknown-word',
      message: `Unknown word "${word}": correct it, or add it to .cspell/words.txt.`,
      location: { file: 'src/b.ts', line: 1, column: 17 },
    });
  });

  it('refuses an issue it cannot read', () => {
    expect(() => spellingFinding('/repo', { text: 'x' })).toThrow(EngineError);
  });
});
