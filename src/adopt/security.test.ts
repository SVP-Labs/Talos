import { parse } from 'smol-toml';
import { describe, expect, it } from 'vitest';
import { licenceOf, securityMigration, spdx } from './security.js';
import { withAdditions } from './talos-yml.js';
import { parseConfig } from '../config/load.js';

/** Shaped like Thea's `.gitleaks.toml` and `osv-scanner.toml`. */
const GITLEAKS = `# gitleaks' own rules, plus the credentials Thea handles.
[extend]
useDefault = true

[[rules]]
id = "thea-token"
regex = '''\\b(?:thea|claim)_[A-Za-z0-9_-]{43}'''
keywords = ["thea_"]

[[rules.allowlists]]
description = "Test fixtures"
regexes = ['''^thea$''']
`;

const OSV = `# Exceptions, each with why and until when.

[[IgnoredVulns]]
id = "GHSA-vfj7-8cjw-p6xm"
ignoreUntil = 2027-01-08
reason = "braces: dev-only, expanding only this repo's own glob patterns"

[[PackageOverrides]]
name = "eslint-plugin-sonarjs"
ecosystem = "npm"
license.ignore = true
reason = "LGPL-3.0, a lint plugin that only runs here and in CI, never shipped"

[[PackageOverrides]]
name = "@sonarsource/analyzer-commons-configurations"
ecosystem = "npm"
license.ignore = true
reason = "LGPL-3.0, part of eslint-plugin-sonarjs, never shipped"
`;

const NESTED = `[[IgnoredVulns]]
id = "RUSTSEC-2024-0370"
ignoreUntil = 2027-01-08T00:00:00Z
reason = "unmaintained, not vulnerable"

[[IgnoredVulns]]
id = "GHSA-vfj7-8cjw-p6xm"
ignoreUntil = 2026-12-01
reason = "the root's reason wins"
`;

const INITIAL = `# This project's additions.\n[extend]\nuseDefault = true\n`;

function migrate(texts: Record<string, string>) {
  return securityMigration(Object.keys(texts), (path) => texts[path]);
}

describe('securityMigration', () => {
  it("moves osv-scanner's exceptions and licence ignores into talos.yml's terms", () => {
    const out = migrate({ 'osv-scanner.toml': OSV, 'apps/desktop/osv-scanner.toml': NESTED });
    expect(out.additions).toEqual({
      exceptions: {
        'GHSA-vfj7-8cjw-p6xm': {
          reason: "braces: dev-only, expanding only this repo's own glob patterns",
          expires: '2027-01-08',
        },
        'RUSTSEC-2024-0370': { reason: 'unmaintained, not vulnerable', expires: '2027-01-08' },
      },
      licences: {
        'LGPL-3.0-only':
          'eslint-plugin-sonarjs: a lint plugin that only runs here and in CI, never shipped; ' +
          '@sonarsource/analyzer-commons-configurations: part of eslint-plugin-sonarjs, never shipped',
      },
    });
    expect(out.moved).toEqual(['osv-scanner.toml', 'apps/desktop/osv-scanner.toml']);
    expect(out.next).toEqual([]);
  });

  it('keeps a file whose entries talos.yml cannot hold, and says what to do with them', () => {
    const out = migrate({
      'osv-scanner.toml': [
        '[[IgnoredVulns]]',
        'id = "GHSA-1"',
        '',
        '[[PackageOverrides]]',
        'name = "left-pad"',
        'ignore = true',
        '',
      ].join('\n'),
      'x/osv-scanner.toml': 'IgnoredVulns = 3\n',
      'y/osv-scanner.toml': '# Generated by Talos 1.0.0. Do not edit.\n',
    });
    expect(out.moved).toEqual([]);
    expect(out.next).toEqual([
      "osv-scanner.toml ignores GHSA-1 without a reason or a real expiry: give it both under talos.yml's supply_chain.exceptions",
      "osv-scanner.toml overrides left-pad, which talos.yml can't say: add its licence under licences with a reason, or drop it",
      "x/osv-scanner.toml can't be read: move its exceptions into talos.yml by hand",
    ]);
  });

  it('moves an ignoreUntil only when it is a day of the calendar', () => {
    const vuln = (id: string, until: string) =>
      `[[IgnoredVulns]]\nid = "${id}"\nignoreUntil = "${until}"\nreason = "not reachable"\n`;
    const out = migrate({
      'osv-scanner.toml': [
        vuln('GHSA-leap', '2028-02-29'),
        vuln('GHSA-time', '2027-01-08T12:00:00Z'),
        vuln('GHSA-feb', '2027-02-30'),
        vuln('GHSA-month', '2027-13-01'),
      ].join('\n'),
    });
    expect(out.additions.exceptions).toEqual({
      'GHSA-leap': { reason: 'not reachable', expires: '2028-02-29' },
      'GHSA-time': { reason: 'not reachable', expires: '2027-01-08' },
    });
    expect(out.moved).toEqual([]);
    expect(out.next).toEqual(
      ['GHSA-feb', 'GHSA-month'].map(
        (id) =>
          `osv-scanner.toml ignores ${id} without a reason or a real expiry: give it both under ` +
          "talos.yml's supply_chain.exceptions",
      ),
    );
  });

  it("moves .gitleaks.toml's own rules into the project file the base extends", () => {
    const out = migrate({ '.gitleaks.toml': GITLEAKS });
    const text = out.gitleaks?.(INITIAL) ?? '';
    expect(text).toBe(
      "# gitleaks' own rules, plus the credentials Thea handles.\n\n" +
        `${INITIAL}\n${GITLEAKS.slice(GITLEAKS.indexOf('[[rules]]'))}`,
    );
    expect(parse(text)).toEqual({ ...parse(GITLEAKS), extend: { useDefault: true } });
    expect(out.gitleaks?.(`${INITIAL}\n[[rules]]\nid = "ours"\n`)).toContain('id = "ours"');
  });

  it('leaves a generated or rule-less .gitleaks.toml, and notes what it could not move', () => {
    expect(migrate({ '.gitleaks.toml': '# Generated by Talos 1.0.0.\n' }).gitleaks).toBeUndefined();
    expect(migrate({ '.gitleaks.toml': '[extend]\nuseDefault = true\n' }).gitleaks).toBeUndefined();
    expect(migrate({ '.gitleaks.toml': '[extend\n' }).next).toEqual([
      ".gitleaks.toml can't be read: move its own rules by hand",
    ]);
    const disabled = migrate({
      '.gitleaks.toml':
        '[extend]\nuseDefault = true\ndisabledRules = ["x"]\n\n[[rules]]\nid = "y"\n',
    });
    expect(disabled.gitleaks).toBeDefined();
    expect(disabled.next).toEqual([
      ".gitleaks.toml's [extend] disabledRules did not move: the base keeps every default rule",
    ]);
    const odd = migrate({ '.gitleaks.toml': 'title = "x"\n[extend]\nuseDefault = true\n' });
    expect(parse(odd.gitleaks?.(INITIAL) ?? '')).toEqual({
      title: 'x',
      extend: { useDefault: true },
    });
  });
});

describe('licences', () => {
  it('reads the licence a reason starts with, as deps.dev names it', () => {
    expect(licenceOf('MPL-2.0: lightningcss')).toEqual({
      licence: 'MPL-2.0',
      rest: 'lightningcss',
    });
    expect(licenceOf('GPL-2.0+, a build tool')?.licence).toBe('GPL-2.0-or-later');
    expect(licenceOf('Dev only, never shipped')).toBeUndefined();
    expect(licenceOf('MIT, fine')).toBeUndefined();
    expect(licenceOf('no separator')).toBeUndefined();
    expect(spdx('AGPL-3.0')).toBe('AGPL-3.0-only');
    expect(spdx('Apache-2.0')).toBe('Apache-2.0');
  });
});

describe('withAdditions', () => {
  const additions = {
    exceptions: { 'GHSA-1': { reason: 'dev: only', expires: '2027-01-08' } },
    licences: { 'MPL-2.0': 'lightningcss' },
  };

  it('adds what talos.yml lacks, as blocks, and keeps the rest of the file', () => {
    const text = '# Ours.\nname: X\nprefix: X\nsupply_chain: { allow: {}, exceptions: {} }\n';
    const merged = withAdditions(text, additions);
    expect(merged.startsWith('# Ours.\nname: X\n')).toBe(true);
    expect(merged).toContain("exceptions:\n    GHSA-1:\n      reason: 'dev: only'\n");
    expect(parseConfig(merged)).toMatchObject({
      supply_chain: { exceptions: { 'GHSA-1': { expires: '2027-01-08' } } },
      licences: { 'MPL-2.0': 'lightningcss' },
    });
    expect(withAdditions(merged, additions)).toBe(merged);
  });

  it("keeps talos.yml's own entry of the same name", () => {
    const text = 'name: X\nprefix: X\nlicences:\n  MPL-2.0: our reason\n';
    const merged = withAdditions(text, { exceptions: {}, licences: additions.licences });
    expect(merged).toBe(text);
  });
});
