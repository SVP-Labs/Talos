import { describe, expect, it } from 'vitest';
import { detectComponents, detectDocs, guessExclude } from './detect.js';

function reader(texts: Readonly<Record<string, string>>) {
  return (path: string): string | undefined => texts[path];
}

describe('detectComponents', () => {
  it('finds a TypeScript workspace at the root and its packages inside it', () => {
    const files = [
      'package.json',
      'pnpm-workspace.yaml',
      'tsconfig.json',
      'apps/hub/package.json',
      'apps/hub/src/index.ts',
      'apps/desktop/Cargo.toml',
      'apps/desktop/src/main.rs',
    ];
    expect(detectComponents(files, reader({}))).toEqual([
      { lang: 'ts', root: '.', os: ['linux'] },
      { lang: 'rust', root: 'apps/desktop', os: ['linux'] },
    ]);
  });

  it('takes a JavaScript project without tsconfig, and a package.json workspaces field', () => {
    const files = ['package.json', 'lib/a.js', 'packages/x/package.json', 'packages/x/i.js'];
    const read = reader({ 'package.json': '{ "workspaces": ["packages/*"] }' });
    expect(detectComponents(files, read)).toEqual([{ lang: 'ts', root: '.', os: ['linux'] }]);
  });

  it('keeps separate packages apart when no workspace holds them', () => {
    const files = ['package.json', 'tools/x.mjs', 'web/package.json', 'web/tsconfig.json'];
    expect(detectComponents(files, reader({})).map((c) => c.root)).toEqual(['.', 'web']);
    expect(detectComponents(['package.json', 'README.md'], reader({}))).toEqual([]);
  });

  it('finds Python by pyproject, packaging setup files, or requirements beside Python code', () => {
    const files = [
      'pyproject.toml',
      'src/app.py',
      'docs/requirements.txt',
      'tools/requirements-dev.txt',
      'tools/run.py',
      'svc/setup.cfg',
      'legacy/setup.py',
      'database/setup.py',
      'database/connection.py',
      'odd/setup.cfg',
    ];
    const read = reader({
      'svc/setup.cfg': '[metadata]\nname = svc\n',
      'legacy/setup.py': 'from setuptools import setup\nsetup()\n',
      'database/setup.py': 'def create_tables():\n    pass\n',
      'odd/setup.cfg': '[flake8]\n',
    });
    const roots = detectComponents(files, read).map((c) => `${c.lang}:${c.root}`);
    expect(roots).toEqual(['py:.', 'py:legacy', 'py:svc', 'py:tools']);
  });

  it('keeps nested Python projects apart unless a uv workspace holds them', () => {
    const files = ['pyproject.toml', 'a.py', 'pkg/pyproject.toml', 'pkg/b.py'];
    expect(detectComponents(files, reader({})).map((c) => c.root)).toEqual(['.', 'pkg']);
    const workspace = reader({ 'pyproject.toml': '[tool.uv.workspace]\nmembers = ["pkg"]\n' });
    expect(detectComponents(files, workspace).map((c) => c.root)).toEqual(['.']);
  });

  it('finds PHP, Lua by rockspec or sources, and a Rust workspace', () => {
    const files = [
      'composer.json',
      'mods/x/mod-1.0-1.rockspec',
      'mods/x/init.lua',
      'Cargo.toml',
      'crates/a/Cargo.toml',
    ];
    const read = reader({ 'Cargo.toml': '[workspace]\nmembers = ["crates/a"]\n' });
    expect(detectComponents(files, read).map((c) => `${c.lang}:${c.root}`)).toEqual([
      'php:.',
      'lua:mods/x',
      'rust:.',
    ]);
    expect(detectComponents(['scripts/init.lua'], read)).toEqual([
      { lang: 'lua', root: '.', os: ['linux'] },
    ]);
  });

  it('applies --os overrides, the last match winning', () => {
    const files = ['package.json', 'tsconfig.json', 'apps/desktop/Cargo.toml'];
    const overrides = [
      { os: ['linux' as const, 'windows' as const] },
      { lang: 'rust' as const, root: 'apps/desktop', os: ['windows' as const] },
      { lang: 'py' as const, os: ['macos' as const] },
    ];
    expect(detectComponents(files, reader({}), overrides).map((c) => c.os)).toEqual([
      ['linux', 'windows'],
      ['windows'],
    ]);
  });
});

describe('guessExclude', () => {
  it('excludes vendored folders, minified bundles and generated files', () => {
    const files = [
      'vendor/autoload.php',
      'vendor/x/y.php',
      'app/third_party/lib/a.js',
      'web/dist/app.js',
      'public/js/app.min.js',
      'src/api.gen.ts',
      'src/normal.ts',
      'eslint.config.js',
      'README.md',
    ];
    const read = reader({
      'src/api.gen.ts': '// Code generated by openapi-gen. DO NOT EDIT.\nexport {};\n',
      'src/normal.ts': 'export const generated = 1;\n',
      'eslint.config.js': '// Generated by Talos 1.0.0. Do not edit.\n',
    });
    expect(guessExclude(files, read)).toEqual([
      'app/third_party',
      'vendor',
      'web/dist',
      '**/*.min.js',
      'src/api.gen.ts',
    ]);
  });

  it("excludes a bundler's committed output folder", () => {
    const files = [
      'app/index.html',
      'app/assets/index-a1b2c3d4.js',
      'app/assets/index-e5f6a7b8.css',
      'src/main.py',
    ];
    expect(guessExclude(files, reader({}))).toEqual(['app']);
    expect(guessExclude(['web/assets/logo-12345678.js'], reader({}))).toEqual([]);
  });

  it('keeps a nested vendored folder inside an excluded one out of the list', () => {
    expect(guessExclude(['vendor/a/node_modules/b/c.js'], reader({}))).toEqual(['vendor']);
    expect(guessExclude(['a.css', 'b.min.css'], reader({}))).toEqual(['**/*.min.css']);
  });
});

describe('detectDocs', () => {
  it("uses the repository's glossary and briefs, or Talos's defaults", () => {
    expect(detectDocs([])).toEqual({ glossary: 'docs/glossary.md', briefs: 'docs/requirements' });
    expect(
      detectDocs(['UBIQUITOUS_LANGUAGE.md', 'docs/briefs/2026-x.md', 'docs/specs/a.txt']),
    ).toEqual({
      glossary: 'UBIQUITOUS_LANGUAGE.md',
      briefs: 'docs/briefs',
    });
  });
});
