import type { TalosConfig } from '../config/schema.js';

/**
 * `CLAUDE.md` as adoption writes it: Talos's generated block, then the project's own block. A
 * rerun replaces only the generated block, so the project's instructions stay as they were.
 */
type ClaudeContext = { readonly config: TalosConfig; readonly version: string };

export type ClaudeRenderer = (existing: string | undefined, ctx: ClaudeContext) => string;

const BEGIN = '<!-- talos:begin -->';
const END = '<!-- talos:end -->';

function kitBlock(ctx: ClaudeContext): string {
  const p = ctx.config.prefix;
  return [
    BEGIN,
    `<!-- Generated by Talos ${ctx.version}. Do not edit inside this block. -->`,
    '',
    `# ${ctx.config.name}`,
    '',
    'Talos governs this repository: the rules are ' +
      '[ENGINEERING.md](https://github.com/SVP-Labs/Talos/blob/main/ENGINEERING.md).',
    '',
    `- Claim a ticket before any work: \`talos ticket claim <N> --agent <id>\`; work on its ` +
      `branch \`${p}-<N>\`, commit as \`[${p}-<N>]: <what changed>\`, and close \`#<N>\` in the PR.`,
    '- Run `talos check --json` before every push; fix what it reports, never suppress it.',
    '- `talos status --json` says what is open and what is red; ask it, never remember it.',
    `- Briefs live in \`${ctx.config.docs.briefs}\`, terms in \`${ctx.config.docs.glossary}\`.`,
    END,
  ].join('\n');
}

export const renderClaudeMd: ClaudeRenderer = (existing, ctx) => {
  const block = kitBlock(ctx);
  if (existing === undefined || existing.trim() === '') return `${block}\n`;
  const start = existing.indexOf(BEGIN);
  const end = existing.indexOf(END);
  if (start !== -1 && end > start) {
    return `${existing.slice(0, start)}${block}${existing.slice(end + END.length)}`;
  }
  return `${block}\n\n${existing.trimStart()}`;
};
